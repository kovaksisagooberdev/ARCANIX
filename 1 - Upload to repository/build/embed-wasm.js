'use strict';
// Builds the Rust core (core/) to WebAssembly and writes rustcore.js: the .wasm embedded as base64 plus the glue that
// routes the editor's hot loops (colour grade / chroma key pixel pass, waveform peaks) through it.
// Usage: node build/embed-wasm.js        (needs Rust with the wasm32-unknown-unknown target)
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const root = path.join(__dirname, '..'), core = path.join(root, 'core');
const cargo = process.platform === 'win32' && fs.existsSync(path.join(process.env.USERPROFILE || '', '.cargo', 'bin', 'cargo.exe'))
  ? path.join(process.env.USERPROFILE, '.cargo', 'bin', 'cargo.exe') : 'cargo';
execFileSync(cargo, ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: core, stdio: 'inherit', env: { ...process.env, RUSTFLAGS: '-C target-feature=+simd128' },
});
const wasm = fs.readFileSync(path.join(core, 'target', 'wasm32-unknown-unknown', 'release', 'arcanix_core.wasm'));
const glue = `'use strict';
/* Arcanix Rust core — GENERATED by build/embed-wasm.js from core/src/lib.rs. Do not edit by hand.
   Loads the WebAssembly module (embedded below) and swaps the editor's hottest loops for the Rust versions.
   The Rust kernels give results identical to the JavaScript they replace; if WebAssembly is unavailable the
   JavaScript versions keep running. Loaded after app.js and shares its scope. */
const AX_WASM = '${wasm.toString('base64')}';
const AX = (() => {
  try {
    const bin = Uint8Array.from(atob(AX_WASM), c => c.charCodeAt(0));
    const ex = new WebAssembly.Instance(new WebAssembly.Module(bin), {}).exports;
    const blocks = new Map();                                       // name -> {ptr, cap}: grown on demand, reused every frame
    const block = (name, n) => {
      let b = blocks.get(name);
      if (!b || b.cap < n) { if (b) ex.ax_free(b.ptr, b.cap); const cap = Math.ceil(n * 1.25); b = { ptr: ex.ax_alloc(cap), cap }; blocks.set(name, b); }
      return b.ptr;
    };
    return { ex, block, mem: () => ex.memory.buffer };
  } catch (e) { console.warn('Arcanix: Rust core unavailable, using JavaScript', e); return null; }
})();
window.cutroom.rustCore = !!AX;

if (AX) {
  const jsPixelPass = pixelPass;
  // colour grade + chroma key: one pass over the clip layer in Rust (same maths as the JS pixelPass)
  pixelPass = function (g, W, H, p) {
    const L = lutOn(p) && gradeLut(p), T = satOn(p) && satTable(p), kp = keyOn(p) && keyParams(p); if (!L && !T && !kp) return;
    try {
      const im = g.getImageData(0, 0, W, H), n = im.data.length;
      const px = AX.block('px', n), lut = L ? AX.block('lut', 768) : 0, hue = T ? AX.block('hue', 360 * 8) : 0;
      new Uint8Array(AX.mem(), px, n).set(im.data);
      if (L) new Uint8Array(AX.mem(), lut, 768).set(L);
      if (T) new Float64Array(AX.mem(), hue, 360).set(T);          // throws if misaligned: the catch below falls back to JS
      const vib = L ? clamp(+p.vibrance || 0, -100, 100) / 100 : 0;
      AX.ex.ax_pixel_pass(px, n, lut, vib, hue, kp ? 1 : 0, kp ? kp.ux : 0, kp ? kp.uy : 0, kp ? kp.K : 1, kp ? kp.thr : 0, kp ? kp.w : 1, kp ? kp.sp : 0);
      im.data.set(new Uint8Array(AX.mem(), px, n));
      g.putImageData(im, 0, 0);
    } catch (e) { console.warn('Arcanix: Rust pixel pass failed, using JavaScript', e); pixelPass = jsPixelPass; jsPixelPass(g, W, H, p); }
  };
  window.cutroom.jsPixelPass = jsPixelPass;

  // waveform peaks: decode in the browser, scan the samples in Rust
  computePeaks = async function (m) {
    if (m.peaks || m.kind === 'image' || !(m.dur > 0) || m.dur > PEAK_MAX_DUR || m.blob.size > 2e9) return;
    try {
      const ab = await m.blob.arrayBuffer();
      const buf = await new OfflineAudioContext(1, 1, PEAK_SR).decodeAudioData(ab);
      const step = buf.sampleRate / PEAK_RATE, len = buf.length, n = Math.ceil(len / step);
      const out = AX.block('peaks', n), src = AX.block('pcm', len * 4);
      new Uint8Array(AX.mem(), out, n).fill(0);
      for (let i = 0; i < buf.numberOfChannels; i++) {
        new Float32Array(AX.mem(), src, len).set(buf.getChannelData(i));
        AX.ex.ax_peaks(src, len, step, out, n);
      }
      m.peaks = new Uint8Array(AX.mem(), out, n).slice(); renderTimeline();
    } catch (e) {
      if (!(e && e.name === 'EncodingError')) return;
      m.peaks = new Uint8Array(0);
    }
    if (media.get(m.id) === m) putMedia(m).catch(() => {});
  };
}
`;
fs.writeFileSync(path.join(root, 'rustcore.js'), glue);
console.log('wrote rustcore.js (wasm', wasm.length, 'bytes)');
